"""
Declarative base and shared column conventions.

Every table in the application hangs off ``Base.metadata``; Alembic reads that
metadata to autogenerate migrations.

The naming convention matters more than it looks. Postgres names an unnamed
constraint for you, and Alembic then has no stable handle to ``DROP`` it later —
autogenerated downgrades and constraint alterations silently produce broken SQL.
Fixing the names up front is what makes the Phase 2 primary-key surgery on
``youtube_videos_live`` expressible as a migration at all.
"""

from __future__ import annotations

from datetime import datetime

from sqlalchemy import MetaData, text
from sqlalchemy.orm import DeclarativeBase, mapped_column
from sqlalchemy.sql.schema import MetaData as MetaDataType

NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_N_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

metadata: MetaDataType = MetaData(naming_convention=NAMING_CONVENTION)


class Base(DeclarativeBase):
    """Declarative base for all ORM models."""

    metadata = metadata


def utcnow_column(**kwargs):
    """A ``TIMESTAMPTZ NOT NULL DEFAULT now()`` column.

    Defaults are applied server-side so rows written by Celery workers, Alembic
    data migrations and the API all agree on the clock.
    """
    kwargs.setdefault("nullable", False)
    return mapped_column(
        server_default=text("now()"),
        **kwargs,
    )


__all__ = ["Base", "metadata", "NAMING_CONVENTION", "utcnow_column", "datetime"]
