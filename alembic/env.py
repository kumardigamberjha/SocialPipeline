"""
Alembic environment.

The database URL comes from ``app.config.Settings``, never from alembic.ini, so
migrations cannot be pointed at a different database than the application by
editing one file and forgetting the other.

Online migrations run through the async engine; ``compare_type`` and
``compare_server_default`` are on so autogenerate notices column changes rather
than silently emitting an empty revision.
"""

from __future__ import annotations

import asyncio
from logging.config import fileConfig

from alembic import context
from sqlalchemy import pool
from sqlalchemy.engine import Connection
from sqlalchemy.ext.asyncio import async_engine_from_config

from app.config import get_settings
from app.db.base import Base

# Importing the table module is what populates Base.metadata. Without it every
# autogenerated revision would propose dropping the entire schema.
import app.db.tables  # noqa: F401

config = context.config

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

target_metadata = Base.metadata

config.set_main_option(
    "sqlalchemy.url",
    # Escape '%' so ConfigParser interpolation does not choke on URL-encoded
    # passwords.
    get_settings().database_url.replace("%", "%%"),
)


def _include_object(obj, name, type_, reflected, compare_to) -> bool:
    """Keep Alembic's hands off tables it does not own."""
    if type_ == "table" and name in {"spatial_ref_sys"}:
        return False
    return True


def run_migrations_offline() -> None:
    """Emit SQL to stdout without connecting ('alembic upgrade head --sql')."""
    context.configure(
        url=config.get_main_option("sqlalchemy.url"),
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
        compare_type=True,
        compare_server_default=True,
        include_object=_include_object,
    )
    with context.begin_transaction():
        context.run_migrations()


def _do_run_migrations(connection: Connection) -> None:
    context.configure(
        connection=connection,
        target_metadata=target_metadata,
        compare_type=True,
        compare_server_default=True,
        include_object=_include_object,
        # DDL in Postgres is transactional: a failed migration rolls all the
        # way back instead of leaving the schema half-applied.
        transaction_per_migration=True,
    )
    with context.begin_transaction():
        context.run_migrations()


async def run_migrations_online() -> None:
    connectable = async_engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )
    async with connectable.connect() as connection:
        await connection.run_sync(_do_run_migrations)
    await connectable.dispose()


if context.is_offline_mode():
    run_migrations_offline()
else:
    asyncio.run(run_migrations_online())
